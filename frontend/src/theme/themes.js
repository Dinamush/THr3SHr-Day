const BY_SLUG = new Map(THEMES.map((theme) => [theme.slug, theme]));

export function findTheme(slug) {
  return BY_SLUG.get(slug) || null;
}

export function isKnownTheme(value) {
  return value === AUTO_THEME || BY_SLUG.has(value);
}

export function resolveTheme(value, prefersDark) {
  if (value === AUTO_THEME || !BY_SLUG.has(value)) {
    return prefersDark ? AUTO_DARK : AUTO_LIGHT;
  }
  return value;
}

// Swatch for the Appearance menu: page, raised surface, strong line, accent.
export function themeChips(theme) {
  const t = theme.tokens;
  return [t.bg, t.sf3, t.ln2, t.ac];
}

// Picker rows, Auto first, grouped as THEME_GROUPS orders them.
export function themeMenu() {
  const auto = {
    slug: AUTO_THEME,
    name: "Auto",
    sub: "Match system",
    square: false,
    chips: [
      findTheme(AUTO_DARK).tokens.bg,
      findTheme(AUTO_DARK).tokens.sf3,
      findTheme(AUTO_LIGHT).tokens.bg,
      findTheme(AUTO_DARK).tokens.ac,
    ],
  };
  return THEME_GROUPS.map((group) => ({
    ...group,
    themes: [
      ...(group.id === "console" ? [auto] : []),
      ...THEMES.filter((theme) => theme.group === group.id).map((theme) => ({
        slug: theme.slug,
        name: theme.name,
        sub: theme.sub,
        square: Boolean(theme.square),
        chips: themeChips(theme),
      })),
    ],
  }));
}
