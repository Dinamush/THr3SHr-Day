// THR3SHR palettes - the one place a theme is defined.
//
// Structure is fixed; a theme is only a palette.  Every entry sets the same
// colour tokens (surfaces, text, lines, accent, semantic states).  The build
// turns this list into the [data-theme] CSS blocks (see paletteCss.js and the
// palettes plugin in vite.config.js), the Appearance menu lists it, and the
// contrast test checks it, so adding a palette is one entry here.
//
// Contrast contract (tests/palettes.test.js): tx2, tx3, ac-tx and the semantic
// colours clear 4.5:1 on sf and bg; on-ac clears 4.5:1 on ac, on-bad on bad.
//
// Ported from the SHUCK3R Console token set so both apps share one look.

