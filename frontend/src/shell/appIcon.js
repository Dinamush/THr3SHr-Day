// THR3SHR app icon ("Grain Bin"): grains pouring on a diagonal into a solid
// hopper, knocked out of the amber Console tile.  The one source for the
// favicon, the PNG and ICO rasters (scripts/build-icons.mjs) and the in-app
// brand mark (BrandMark in icons.jsx).
//
// Three detail levels, each drawn on its own grid so the small sizes land on
// whole pixels: micro (16 grid, two grains, the 16px favicon), small (32
// grid, up to 40px) and full (64 grid, 48px and up).  The flat rim keeps the
// hopper an object; level grains over a round bin read as a face.

export const TILE_TOP = "#f3bd63";
export const TILE_BOTTOM = "#de8f25";
export const INK = "#1a1205";

export const LEVELS = {
  micro: {
    grid: 16,
    inset: 0,
    radius: 3.5,
    bin: "M2 8h12l-1.05 4.1a1.2 1.2 0 0 1-1.16.9H4.21a1.2 1.2 0 0 1-1.16-.9z",
    grains: [
      [11, 3],
      [8, 6],
    ],
    grainRadius: 1.15,
  },
  small: {
    grid: 32,
    inset: 0,
    radius: 7,
    bin: "M4 16h24l-2.1 8.2a2.4 2.4 0 0 1-2.33 1.8H8.43a2.4 2.4 0 0 1-2.33-1.8z",
    grains: [
      [22, 4],
      [18, 8],
      [14, 12],
    ],
    grainRadius: 1.75,
  },
  full: {
    grid: 64,
    inset: 2,
    radius: 14,
    rim: true,
    bin: "M11.5 32.5h41l-3.9 15.7a5 5 0 0 1-4.85 3.8H20.25a5 5 0 0 1-4.85-3.8z",
    binStroke: 2.8,
    // Short pills on the pour line.
    grainPath: "M43.6 7.6l-.9 1.1M36.2 16.2l-.9 1.1M28.8 24.8l-.9 1.1",
    grainWidth: 6.6,
  },
};

export function levelFor(px) {
  if (px <= 20) return "micro";
  if (px <= 40) return "small";
  return "full";
}

// The shapes of one level: the tile, an optional highlight rim, the hopper
// and the grains, as plain attribute objects so both the SVG strings below
// and the React mark draw the same thing.
export function iconShapes(level) {
  const L = LEVELS[level];
  const w = L.grid - L.inset * 2;
  const shapes = {
    grid: L.grid,
    tile: { x: L.inset, y: L.inset, width: w, height: w, rx: L.radius },
    rim: L.rim
      ? {
          x: L.inset + 0.6,
          y: L.inset + 0.6,
          width: w - 1.2,
          height: w - 1.2,
          rx: L.radius - 0.6,
        }
      : null,
    bin: { d: L.bin, strokeWidth: L.binStroke || 0 },
  };
  if (L.grainPath) {
    shapes.grainPath = { d: L.grainPath, strokeWidth: L.grainWidth };
  } else {
    shapes.grains = L.grains.map(([cx, cy]) => ({ cx, cy, r: L.grainRadius }));
  }
  return shapes;
}

function grainsSvg(s, ink) {
  if (s.grainPath) {
    return `<path d="${s.grainPath.d}" fill="none" stroke="${ink}" stroke-width="${s.grainPath.strokeWidth}" stroke-linecap="round"/>`;
  }
  return s.grains.map((g) => `<circle cx="${g.cx}" cy="${g.cy}" r="${g.r}" fill="${ink}"/>`).join("");
}

function binSvg(s, ink) {
  const stroke = s.bin.strokeWidth
    ? ` stroke="${ink}" stroke-width="${s.bin.strokeWidth}" stroke-linejoin="round"`
    : "";
  return `<path d="${s.bin.d}" fill="${ink}"${stroke}/>`;
}

function rect(r, attrs) {
  return `<rect x="${r.x}" y="${r.y}" width="${r.width}" height="${r.height}" rx="${r.rx}"${attrs}/>`;
}

// A standalone SVG document with fixed colours, for rasterising.  `bleed`
// fills the whole square with the tile (no inset, corners or rim) for
// platforms that cut their own shape, like iOS home-screen icons.
export function appIconSvg(level, { px, bleed = false } = {}) {
  const s = iconShapes(level);
  if (bleed) {
    s.tile = { x: 0, y: 0, width: s.grid, height: s.grid, rx: 0 };
    s.rim = null;
  }
  const size = px ? ` width="${px}" height="${px}"` : "";
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${s.grid} ${s.grid}"${size}>` +
    `<defs><linearGradient id="tile" x1="0" y1="0" x2="0" y2="1">` +
    `<stop offset="0" stop-color="${TILE_TOP}"/><stop offset="1" stop-color="${TILE_BOTTOM}"/>` +
    `</linearGradient></defs>` +
    rect(s.tile, ` fill="url(#tile)"`) +
    (s.rim ? rect(s.rim, ` fill="none" stroke="#fff" stroke-opacity=".32" stroke-width="1.2"`) : "") +
    binSvg(s, INK) +
    grainsSvg(s, INK) +
    `</svg>`
  );
}

// frontend/public/favicon.svg: the micro level.  A light browser gets a
// slightly deeper tile so its edge holds against a white tab strip.
export function faviconSvg() {
  const s = iconShapes("micro");
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${s.grid} ${s.grid}">`,
    `  <!-- THR3SHR favicon - Grain Bin. Generated by scripts/build-icons.mjs from src/shell/appIcon.js. -->`,
    `  <style>`,
    `    :root { --fv-top: #efb24f; --fv-bottom: #d8871b; }`,
    `    @media (prefers-color-scheme: dark) {`,
    `      :root { --fv-top: ${TILE_TOP}; --fv-bottom: ${TILE_BOTTOM}; }`,
    `    }`,
    `  </style>`,
    `  <defs>`,
    `    <linearGradient id="tile" x1="0" y1="0" x2="0" y2="1">`,
    `      <stop offset="0" style="stop-color: var(--fv-top)"/>`,
    `      <stop offset="1" style="stop-color: var(--fv-bottom)"/>`,
    `    </linearGradient>`,
    `  </defs>`,
    `  ${rect(s.tile, ` fill="url(#tile)"`)}`,
    `  ${binSvg(s, INK)}`,
    `  ${grainsSvg(s, INK)}`,
    `</svg>`,
    "",
  ].join("\n");
}
